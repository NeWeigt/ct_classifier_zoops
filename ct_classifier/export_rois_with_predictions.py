"""Export ROI images using their predicted class labels from a predictions CSV.

This script reads the CSV generated by predict_unlabelled_resnet50.py (or a
compatible CSV with at least `image_path` and `pred_class_label` columns), then
copies each ROI into an output directory with a configurable filename format.

Usage (from project root `ct_classifier_zoops`):

    python ct_classifier/export_rois_with_predictions.py \
        --predictions-csv /mnt/class_data/Nele/ROIs_August2025/optturb_predictions_resnet50_St01.csv \
        --output-dir /mnt/class_data/Nele/ROIs_August2025/exported_predictions_St01

Default output naming format:
    {pred_label}_{orig_name}

Supported placeholders in `--name-template`:
    {pred_label}  predicted class label (or class index if label is missing)
    {pred_index}  predicted class index
    {confidence}  confidence as fixed decimal string
    {stem}        original filename without extension
    {orig_name}   original filename with extension
"""

import argparse
import csv
import os
import re
import shutil
from dataclasses import dataclass
from typing import Dict, Iterable, Optional


DEFAULT_TEMPLATE = "{pred_label}_{orig_name}"
ALLOWED_EXTS = {".tif", ".tiff"}


@dataclass
class PredictionRow:
    image_path: str
    pred_label: str
    pred_index: str
    confidence: str


def sanitize_filename_part(value: str) -> str:
    """Make a safe path component from a label or formatted name part."""

    value = value.strip()
    value = re.sub(r"[\\/:*?\"<>|]", "_", value)
    value = re.sub(r"\s+", "_", value)
    value = value.strip("._")
    return value or "unknown"


def normalize_confidence(raw_value: str) -> str:
    """Convert confidence to a stable decimal string when possible."""

    try:
        return f"{float(raw_value):.6f}"
    except (TypeError, ValueError):
        return ""


def iter_predictions(csv_path: str) -> Iterable[PredictionRow]:
    """Yield rows from the predictions CSV in a normalized shape."""

    with open(csv_path, "r", newline="") as f:
        reader = csv.DictReader(f)
        required = {"image_path", "pred_class_index"}
        missing = required - set(reader.fieldnames or [])
        if missing:
            raise ValueError(
                "CSV is missing required columns: " + ", ".join(sorted(missing))
            )

        for row in reader:
            image_path = (row.get("image_path") or "").strip()
            pred_index = (row.get("pred_class_index") or "").strip()
            pred_label = (row.get("pred_class_label") or "").strip() or pred_index
            confidence = normalize_confidence((row.get("confidence") or "").strip())

            if not image_path:
                continue

            yield PredictionRow(
                image_path=image_path,
                pred_label=pred_label,
                pred_index=pred_index,
                confidence=confidence,
            )


def build_export_name(name_template: str, row: PredictionRow) -> str:
    """Build destination filename from template placeholders."""

    base_name = os.path.basename(row.image_path)
    stem, ext = os.path.splitext(base_name)

    values: Dict[str, str] = {
        "pred_label": sanitize_filename_part(row.pred_label),
        "pred_index": sanitize_filename_part(row.pred_index),
        "confidence": sanitize_filename_part(row.confidence),
        "stem": sanitize_filename_part(stem),
        "orig_name": sanitize_filename_part(base_name),
    }

    try:
        rendered = name_template.format(**values)
    except KeyError as exc:
        raise ValueError(f"Unknown placeholder in --name-template: {exc}") from exc

    rendered = sanitize_filename_part(rendered)

    # Preserve image extension if template omitted one.
    rendered_stem, rendered_ext = os.path.splitext(rendered)
    source_ext = ext.lower()
    if rendered_ext.lower() in ALLOWED_EXTS:
        return rendered
    if source_ext in ALLOWED_EXTS:
        return f"{rendered_stem}{source_ext}"
    return f"{rendered_stem}.png"


def ensure_unique_path(path: str) -> str:
    """Append numeric suffix when destination path already exists."""

    if not os.path.exists(path):
        return path

    root, ext = os.path.splitext(path)
    i = 1
    while True:
        candidate = f"{root}__{i}{ext}"
        if not os.path.exists(candidate):
            return candidate
        i += 1


def export_rois(
    predictions_csv: str,
    output_dir: str,
    name_template: str,
    group_by_label: bool,
    min_confidence: Optional[float],
) -> None:
    """Copy ROI images to output path using predicted labels."""

    if not os.path.isfile(predictions_csv):
        raise FileNotFoundError(f"Predictions CSV not found: {predictions_csv}")

    os.makedirs(output_dir, exist_ok=True)

    exported = 0
    skipped_missing = 0
    skipped_confidence = 0

    for row in iter_predictions(predictions_csv):
        if min_confidence is not None:
            try:
                conf_val = float(row.confidence)
            except ValueError:
                skipped_confidence += 1
                continue
            if conf_val < min_confidence:
                skipped_confidence += 1
                continue

        if not os.path.isfile(row.image_path):
            skipped_missing += 1
            continue

        dst_dir = output_dir
        if group_by_label:
            dst_dir = os.path.join(output_dir, sanitize_filename_part(row.pred_label))
        os.makedirs(dst_dir, exist_ok=True)

        export_name = build_export_name(name_template=name_template, row=row)
        dst_path = ensure_unique_path(os.path.join(dst_dir, export_name))

        shutil.copy2(row.image_path, dst_path)
        exported += 1

    print(f"Done. Exported {exported} ROI files to '{output_dir}'.")
    if skipped_missing:
        print(f"Skipped {skipped_missing} rows because image files were missing.")
    if skipped_confidence:
        print(
            f"Skipped {skipped_confidence} rows due to confidence filtering "
            "or invalid confidence values."
        )


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description=(
            "Export/copy ROI files from a predictions CSV using predicted class names."
        )
    )
    parser.add_argument(
        "--predictions-csv",
        required=True,
        help="Path to predictions CSV with at least image_path and pred_class_index.",
    )
    parser.add_argument(
        "--output-dir",
        required=True,
        help="Destination directory for exported ROI files.",
    )
    parser.add_argument(
        "--name-template",
        default=DEFAULT_TEMPLATE,
        help=(
            "Filename template (default: '{pred_label}_{orig_name}'). "
            "Placeholders: {pred_label}, {pred_index}, {confidence}, {stem}, {orig_name}."
        ),
    )
    parser.add_argument(
        "--flat",
        action="store_true",
        help="Do not create per-class subfolders; write all files directly to output-dir.",
    )
    parser.add_argument(
        "--min-confidence",
        type=float,
        default=None,
        help="Optional minimum confidence in [0,1]. Rows below this value are skipped.",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()

    min_conf = args.min_confidence
    if min_conf is not None and not (0.0 <= min_conf <= 1.0):
        raise ValueError("--min-confidence must be between 0 and 1.")

    export_rois(
        predictions_csv=args.predictions_csv,
        output_dir=args.output_dir,
        name_template=args.name_template,
        group_by_label=not args.flat,
        min_confidence=min_conf,
    )


if __name__ == "__main__":
    main()
